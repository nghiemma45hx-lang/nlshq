/**
 * Remove duplicate stacked/repeated NLS badges in adjacent elements or within the same section/cell.
 * Ensures "chỉ xuất hiện một miền NLS, không lặp lại một NLS ở cùng một vị trí".
 */
export function deduplicateNlsBadges(htmlStr: string): string {
  if (!htmlStr) return htmlStr;

  let result = htmlStr;

  // 1. Remove duplicate adjacent "Tích hợp Tích hợp" strings
  result = result.replace(/(?:Tích hợp\s+)+/gi, 'Tích hợp ');

  // 2. Remove duplicate identical span/div badges inside table cells, paragraphs, or blocks
  // e.g. If an NLS code like "NLS 1.1-a" occurs multiple times in the same <td> or <div> or <p>, keep only the 1st
  const nlsCodeKeys = Object.keys(NLS_CODE_TITLES);

  for (const code of nlsCodeKeys) {
    const escapedCode = code.replace(/\./g, '\\.');
    const badgePattern = new RegExp(
      `(?:<span\\b[^>]*>(?:\\s*Tích hợp\\s*)?\\[${escapedCode}[^\\]]*\\]<\\/span>|<div\\b[^>]*>(?:\\s*Tích hợp\\s*)?\\[${escapedCode}[^\\]]*\\]<\\/div>|Tích hợp\\s*\\[${escapedCode}[^\\]]*\\]|\\[${escapedCode}[^\\]]*\\])`,
      'gi'
    );

    // Filter within block tags <td>, <th>, <p>, <div>, <li>
    result = result.replace(/<(td|th|p|div|li)\b([^>]*)>([\s\S]*?)<\/\1>/gi, (match, tag, attrs, innerContent) => {
      let seen = false;
      const cleanedInner = innerContent.replace(badgePattern, (badgeMatch) => {
        if (!seen) {
          seen = true;
          return badgeMatch;
        }
        return ''; // Remove redundant duplicate badge
      });
      return `<${tag}${attrs}>${cleanedInner}</${tag}>`;
    });
  }

  // 3. Clean up empty/whitespace-only tags left over from duplicate removals
  result = result.replace(/<span\b[^>]*>\s*<\/span>/gi, '');
  result = result.replace(/<div\b[^>]*>\s*<\/div>/gi, '');

  return result;
}

/**
 * Detect if a lesson plan or section is an exam/assessment period.
 * (Kiểm tra giữa kỳ I/II, Kiểm tra cuối kỳ I/II, Kiểm tra định kỳ, Đánh giá giữa kỳ...)
 * Exam periods are exempt and MUST NOT have NLS integration added.
 */
export function isExamPeriod(textOrHtml: string): boolean {
  if (!textOrHtml) return false;
  const examKeywordsRegex = /(kiểm\s+tra\s+(giữa|cuối)\s+kỳ|kiểm\s+tra\s+(giữa|cuối)\s+kì|đánh\s+giá\s+(giữa|cuối)\s+kỳ|đánh\s+giá\s+(giữa|cuối)\s+kì|kiểm\s+tra\s+định\s+kỳ|bài\s+kiểm\s+tra|tiết\s+kiểm\s+tra|đề\s+kiểm\s+tra)/i;
  return examKeywordsRegex.test(textOrHtml);
}

/**
 * Remove any NLS/AI tags from exam periods and attach an exemption notice.
 */
export function processExamPeriodHtml(htmlStr: string): string {
  if (!htmlStr) return htmlStr;
  
  // Strip all NLS or AI tags and red boxes
  let clean = htmlStr.replace(/(?:Tích hợp\s*)?\[(?:NLS|AI-NL)[^\]]*\]/gi, '');
  clean = clean.replace(/<div[^>]*border-red-500[^>]*>[\s\S]*?<\/div>/gi, '');
  clean = clean.replace(/<span[^>]*border-slate-300[^>]*>\s*<\/span>/gi, '');

  const noticeBanner = `<div class="my-3.5 p-3.5 bg-slate-100 border border-slate-300 rounded text-sm text-slate-800 font-bold text-center shadow-sm">TIẾT KIỂM TRA / ĐÁNH GIÁ ĐỊNH KỲ (ĐỘC LẬP) - Giữ nguyên hình thức kiểm tra đánh giá độc lập của học sinh, không thực hiện tích hợp NLS & AI</div>`;
  
  if (!clean.includes('TIẾT KIỂM TRA / ĐÁNH GIÁ ĐỊNH KỲ')) {
    clean = noticeBanner + '\n' + clean;
  }
  return clean;
}

/**
 * Strip NLS/AI tags from internal/nested tables (Phiếu học tập, Bảng dữ liệu nội dung).
 * NLS tags should only appear in the main "Tổ chức thực hiện" column 1 or main activity headings,
 * NEVER inside nested worksheet tables or internal content data tables.
 */
export function stripNlsFromInternalTables(htmlStr: string): string {
  if (!htmlStr) return htmlStr;

  // Target any table that represents a worksheet or inner content table or is nested
  return htmlStr.replace(/<table\b[^>]*>([\s\S]*?)<\/table>/gi, (tableMatch) => {
    const isWorksheetOrInternal = /phiếu\s+học\s+tập|bảng\s+kết\s+quả|bảng\s+phân\s+tích|bảng\s+đối\s+chiếu|phiếu\s+số/i.test(tableMatch) ||
      /<table\b/i.test(tableMatch.slice(6)); // nested table inside table

    if (isWorksheetOrInternal) {
      let cleanInner = tableMatch.replace(/(?:Tích hợp\s*)?\[(?:NLS|AI-NL)[^\]]*\]/gi, '');
      cleanInner = cleanInner.replace(/<div[^>]*border-red-500[^>]*>[\s\S]*?<\/div>/gi, '');
      cleanInner = cleanInner.replace(/<span[^>]*border-slate-300[^>]*>\s*<\/span>/gi, '');
      return cleanInner;
    }
    return tableMatch;
  });
}

/**
 * Utility to process and re-align Lesson Plan HTML.
 * Moves NLS tags from Right Column to Left Column if needed,
 * filters exam periods, injects NLS tags into group task questions, etc.
 */
export function relocateNlsToLeftColumn(htmlStr: string): string {
  if (!htmlStr) return htmlStr;

  // Check if the entire document is an Exam Period (Kiểm tra giữa kỳ I, Kiểm tra cuối kỳ I...)
  if (isExamPeriod(htmlStr)) {
    return processExamPeriodHtml(htmlStr);
  }

  // Remove synthetic/duplicate banner blocks like [Tích hợp NLS & AI Khởi động...]
  let processed = htmlStr.replace(/<div\b[^>]*>[\s\S]*?\[Tích hợp NLS & AI[^\]]*\][\s\S]*?<\/div>/gi, '');

  // Fill empty left columns (especially Hoạt động 2 in Image 5)
  processed = fixEmptyLeftColumns(processed);

  // First expand bare NLS codes to include titles (e.g. Tích hợp [NLS 2.4-a: Hợp tác qua công nghệ số])
  processed = expandNlsTagTitles(processed);

  // Inject NLS domain tags into goals section (Mục tiêu) of each activity (3 distinct NLS domains per activity)
  processed = injectNlsActivityGoals(processed);

  // Position NLS integration at the bottom of Part 4 (Hướng dẫn học bài & chuẩn bị bài)
  processed = formatPart4NlsBottom(processed);

  // Inject NLS tags into group assignments (Nhóm 1, 2..., Nhóm 3, 4...)
  processed = injectNlsIntoGroupTasks(processed);

  // Inject NLS tags into activity steps (Bước 1, Bước 2...) if needed
  processed = injectNlsIntoActivitySteps(processed);

  // Ensure every [NLS ...] or [AI-NL...] tag has "Tích hợp " in front
  processed = ensureTichHopPrefix(processed);

  // Process HTML table rows <tr>...</tr> to relocate right-column NLS tags to left column
  processed = processed.replace(/<tr\b[^>]*>([\s\S]*?)<\/tr>/gi, (fullTrMatch, trContent) => {
    // Extract cells inside this row
    const cellRegex = /<(td|th)\b([^>]*)>([\s\S]*?)<\/\1>/gi;
    const cells: { tag: string; attrs: string; content: string }[] = [];
    let cellMatch;

    while ((cellMatch = cellRegex.exec(trContent)) !== null) {
      cells.push({
        tag: cellMatch[1],
        attrs: cellMatch[2],
        content: cellMatch[3],
      });
    }

    // If row has at least 2 cells (Left = index 0: Tổ chức thực hiện, Right = index 1: Nội dung/Sản phẩm)
    if (cells.length >= 2) {
      const isHeaderRow = /tổ chức thực hiện|sản phẩm|nội dung/i.test(cells[0].content + cells[1].content);
      if (isHeaderRow && cells[0].tag.toLowerCase() === 'th') {
        return fullTrMatch;
      }

      let leftCell = cells[0].content;
      let rightCell = cells[1].content;

      // Extract NLS / AI-NL tags from right cell and remove them entirely along with any wrapper elements
      const nlsTagsToMove: string[] = [];

      // 1. First strip full outer HTML tags <span...> or <div...> containing NLS/AI tags in rightCell
      rightCell = rightCell.replace(/<(span|div)\b[^>]*>(?:[^<]|<(?!\/\1>))*?\[(?:NLS|AI-NL)[^\]]*\][\s\S]*?<\/\1>/gi, (match) => {
        const tagTextMatches = match.match(/(?:Tích hợp\s*)?\[(?:NLS|AI-NL)[^\]]*\]/gi);
        if (tagTextMatches) {
          nlsTagsToMove.push(...tagTextMatches);
        }
        return '';
      });

      // 2. Also strip any remaining bare bracket NLS tags in rightCell
      rightCell = rightCell.replace(/(?:Tích hợp\s*)?\[(?:NLS|AI-NL)[^\]]*\]/gi, (tag) => {
        nlsTagsToMove.push(tag);
        return '';
      });

      // 3. Clean up any empty span/div wrappers left behind in rightCell
      rightCell = rightCell.replace(/<(span|div)\b[^>]*>\s*<\/\1>/gi, '');

      if (nlsTagsToMove.length > 0) {
        // Filter out duplicate NLS tags and tags already present in leftCell
        const uniqueTagsToMove = Array.from(new Set(nlsTagsToMove));
        const newTagsForLeft: string[] = [];

        for (const rawTag of uniqueTagsToMove) {
          const formattedTag = rawTag.startsWith('Tích hợp ') ? rawTag : `Tích hợp ${rawTag}`;
          // Check if leftCell already has this tag
          const codeMatch = rawTag.match(/(?:NLS|AI-NL)\s*[\d\.\w\-]+/i);
          const tagCode = codeMatch ? codeMatch[0] : rawTag;

          if (!leftCell.includes(tagCode)) {
            newTagsForLeft.push(`<span class="font-mono font-bold text-red-600 border border-slate-300 px-1.5 py-0.5 rounded text-[11px] inline-block my-0.5 mr-1.5">${formattedTag}</span>`);
          }
        }

        if (newTagsForLeft.length > 0) {
          leftCell = leftCell + `\n<div class="mt-2 flex flex-wrap gap-1">${newTagsForLeft.join(' ')}</div>`;
        }

        cells[0].content = leftCell;
        cells[1].content = rightCell;

        const trTagMatch = fullTrMatch.match(/^<tr\b[^>]*>/i);
        const trOpenTag = trTagMatch ? trTagMatch[0] : '<tr>';
        
        let rebuiltCells = '';
        for (let i = 0; i < cells.length; i++) {
          rebuiltCells += `<${cells[i].tag}${cells[i].attrs}>${cells[i].content}</${cells[i].tag}>`;
        }
        return trOpenTag + rebuiltCells + '</tr>';
      }
    }

    return fullTrMatch;
  });

  // Deduplicate all repeated/stacked NLS badges so each NLS code appears ONLY ONCE at any spot
  processed = deduplicateNlsBadges(processed);

  // Remove background color fills for NLS tags
  processed = stripNlsBackgrounds(processed);

  // Strip NLS/AI tags from internal worksheet tables / content data tables
  processed = stripNlsFromInternalTables(processed);

  return processed;
}

/**
 * Dynamically extract specific Lesson Title, Topic, or Lesson Number
 * from lesson content HTML or raw text.
 */
export function extractLessonTitle(contentHtml: string, subject: string, grade: string): string {
  if (!contentHtml) {
    const subClean = subject || 'Ngữ văn';
    const grdClean = grade || 'Khối THCS';
    return `Bài dạy ${subClean} (${grdClean}) - Tích hợp NLS`;
  }

  // Strip HTML tags to get plain text lines
  const cleanText = contentHtml
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/p>/gi, '\n')
    .replace(/<\/div>/gi, '\n')
    .replace(/<\/tr>/gi, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ');

  const lines = cleanText
    .split('\n')
    .map(l => l.trim())
    .filter(l => l.length > 2);

  let detectedBai = '';
  let detectedDocVanBan = '';
  let detectedExplicit = '';

  // Non-title boilerplate keywords to filter out
  const isBoilerplate = (str: string) => {
    return /^(TRƯỜNG|PHÒNG GIÁO DỤC|TỔ CHUYÊN MÔN|CÔNG VĂN|THÔNG TƯ|QUYẾT ĐỊNH|BỘ GIÁO DỤC|CỘNG HÒA|ĐỘC LẬP|GIÁO VIÊN|HỌ VÀ TÊN|NGÀY SOẠN|LỚP|SĨ SỐ|I\.|II\.|III\.|IV\.|1\. Kiến thức|1\. Năng lực|MỤC TIÊU|THIẾT BỊ|TIẾN TRÌNH)/i.test(str);
  };

  // Search first 40 lines for explicit markers and key patterns
  for (const line of lines.slice(0, 45)) {
    if (isBoilerplate(line)) continue;

    // 1. Check for "TÊN BÀI DẠY: ...", "KẾ HOẠCH BÀI DẠY: ...", "BÀI DẠY: ...", "TÊN BÀI: ..."
    const matchExplicit = line.match(/(?:TÊN BÀI DẠY|Tên bài dạy|KẾ HOẠCH BÀI DẠY|BÀI DẠY|Bài dạy|TÊN BÀI|Tên bài|TÊN BÀI HỌC)\s*[:\-]\s*(.+)/i);
    if (matchExplicit && matchExplicit[1]?.trim().length > 3) {
      const candidate = matchExplicit[1].trim();
      if (!isBoilerplate(candidate) && candidate.toLowerCase() !== 'tích hợp nls') {
        detectedExplicit = candidate;
        break;
      }
    }

    // 2. Check for "Bài 9: HÔM NAY VÀ NGÀY MAI (13 tiết)", "Bài 1. ...", "Chủ đề 2: ...", "Tiết 12: ..."
    if (!detectedBai) {
      const matchBai = line.match(/^(Bài\s+\d+[^:\n]*:[^\n]+)/i) || 
                       line.match(/^(Bài\s+\d+\.[^\n]+)/i) ||
                       line.match(/^(Chủ đề\s+\d+[^:\n]*:[^\n]+)/i) ||
                       line.match(/^(Tiết\s+\d+[^:\n]*:[^\n]+)/i) ||
                       line.match(/^(Văn bản\s+\d+:[^\n]+)/i);
      if (matchBai && matchBai[1]?.trim().length > 4) {
        detectedBai = matchBai[1].trim();
      }
    }

    // 3. Check for specific text reading title like "B. Đọc văn bản: Nhà thơ của quê hương..." or "Đọc văn bản: ..." or "Văn bản 1: ..."
    if (!detectedDocVanBan) {
      const matchDoc = line.match(/(?:Đọc văn bản|Văn bản|Đọc - tìm hiểu chung|Văn bản 1|Văn bản 2|Văn bản 3)\s*[:\-]\s*([^\n]+)/i);
      if (matchDoc && matchDoc[1]?.trim().length > 3) {
        const val = matchDoc[1].trim();
        if (!/^(i|ii|iii|1|2|3|mục tiêu|thiết bị)/i.test(val)) {
          detectedDocVanBan = `Đọc văn bản: ${val}`;
        }
      }
    }
  }

  // Combine detected components if available
  if (detectedExplicit) {
    return detectedExplicit;
  }

  if (detectedBai && detectedDocVanBan) {
    // Avoid duplication if detectedDocVanBan is already inside detectedBai
    if (detectedBai.toLowerCase().includes(detectedDocVanBan.toLowerCase().replace('đọc văn bản:', '').trim())) {
      return detectedBai;
    }
    return `${detectedBai} - ${detectedDocVanBan}`;
  }

  if (detectedBai) {
    return detectedBai;
  }

  if (detectedDocVanBan) {
    return detectedDocVanBan;
  }

  // Check uppercase headings or lines starting with "BÀI ", "CHỦ ĐỀ ", "NGỮ VĂN "
  for (const line of lines.slice(0, 30)) {
    if (isBoilerplate(line)) continue;
    if (/^(bài|chủ đề|tiết|văn bản)\s+/i.test(line) && line.length > 5 && line.length < 140) {
      return line;
    }
  }

  for (const line of lines.slice(0, 20)) {
    if (isBoilerplate(line)) continue;
    if (line === line.toUpperCase() && line.length >= 8 && line.length <= 100 && !line.includes('CỘNG HÒA')) {
      return line;
    }
  }

  const subClean = subject || 'Ngữ văn';
  const grdClean = grade || 'Khối THCS';
  return `Bài dạy ${subClean} (${grdClean}) - Tích hợp NLS`;
}

/**
 * Format timestamp / dateString into full HH:mm - DD/MM/YYYY display.
 */
export function formatDateTime(dateString: string, createdAt?: number): string {
  if (createdAt && typeof createdAt === 'number' && !isNaN(createdAt) && createdAt > 1000000000) {
    const d = new Date(createdAt);
    const timeStr = d.toLocaleTimeString('vi-VN', { hour: '2-digit', minute: '2-digit' });
    const dateStr = d.toLocaleDateString('vi-VN', { day: '2-digit', month: '2-digit', year: 'numeric' });
    return `${timeStr} - ${dateStr}`;
  }

  if (dateString && dateString.includes(':') && dateString.includes('-')) {
    return dateString;
  }

  // Fallback format current date with time if only date was provided
  const now = new Date();
  const timeStr = now.toLocaleTimeString('vi-VN', { hour: '2-digit', minute: '2-digit' });
  if (dateString) {
    return `${timeStr} - ${dateString}`;
  }
  return `${timeStr} - ${now.toLocaleDateString('vi-VN')}`;
}

