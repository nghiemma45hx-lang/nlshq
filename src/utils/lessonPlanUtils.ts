/**
 * Expand bare NLS tags like [NLS 2.4-a] to include their full capability title: [NLS 2.4-a: Hợp tác qua công nghệ số]
 */
export function expandNlsTagTitles(htmlStr: string): string {
  if (!htmlStr) return htmlStr;
  return htmlStr.replace(/\[(NLS\s+[0-9\.\-a-z]+|AI-NL[a-z]+)(?:\s*:\s*([^\]]+))?\]/gi, (fullMatch, rawCode, existingTitle) => {
    // Normalize code key (e.g. "NLS 2.4-a" or "AI-NLc")
    const codeKey = rawCode.trim();
    const fullTitle = NLS_CODE_TITLES[codeKey];

    if (fullTitle) {
      return `[${codeKey}: ${fullTitle}]`;
    }

    if (existingTitle && existingTitle.trim().length > 0) {
      return `[${codeKey}: ${existingTitle.trim()}]`;
    }

    return fullMatch;
  });
}

/**
 * Remove background color fills from all NLS & AI badges in HTML.
 * Ensures "không đổ mầu nền chữ các phần tích hợp NLS".
 */
export function stripNlsBackgrounds(htmlStr: string): string {
  if (!htmlStr) return htmlStr;
  return htmlStr
    .replace(/bg-(?:indigo|rose|purple|amber|emerald|slate)-(?:50|100|200|500|600|900)\/?[0-9]*/g, 'bg-transparent')
    .replace(/background:\s*#[a-f0-9]{3,6};?/gi, 'background: transparent;');
}

/**
 * Inject small red framed NLS domain badges (khung đỏ nhỏ)
 * into the objective ("Mục tiêu:") section of each activity (Hoạt động 1, 2, 3, 4).
 * Single outer red frame (border border-red-500) wraps all NLS/AI domains for that activity.
 * Text colors: Red (text-red-600) and Navy Blue / Tím Than (text-indigo-950 / text-slate-900).
 */
export function injectNlsActivityGoals(htmlStr: string): string {
  if (!htmlStr) return htmlStr;

  let result = htmlStr;

  // Single outer red frame enclosing all NLS/AI domains for an activity goal
  const redFrameContainer = (...tags: { text: string; colorClass: string }[]) => {
    const tagSpans = tags
      .map(t => `<span class="${t.colorClass} font-bold">${t.text}</span>`)
      .join(' ');
    return `<div class="my-1.5 inline-flex flex-wrap items-center gap-2 border border-red-500 rounded px-2.5 py-1 text-xs font-mono font-bold bg-rose-50/20">${tagSpans}</div>`;
  };

  // 1. Hoạt động 1: Khởi động / Mở đầu -> [NLS 1.1-a: Duyệt, tìm kiếm & lọc dữ liệu số]
  const act1Badge = redFrameContainer({
    text: '[NLS 1.1-a: Duyệt, tìm kiếm & lọc dữ liệu số]',
    colorClass: 'text-red-600',
  });

  // 2. Hoạt động 2: Hình thành kiến thức mới -> [NLS 3.1-a] + [AI-NLc] in ONE single outer frame
  const act2Badge = redFrameContainer(
    { text: '[NLS 3.1-a: Phát triển & chỉnh sửa nội dung số]', colorClass: 'text-red-600' },
    { text: '[AI-NLc: Giao tiếp với AI & Prompt Engineering]', colorClass: 'text-indigo-950' }
  );

  // 3. Hoạt động 3: Luyện tập -> [NLS 2.4-a]
  const act3Badge = redFrameContainer({
    text: '[NLS 2.4-a: Hợp tác qua công nghệ số]',
    colorClass: 'text-red-600',
  });

  // 4. Hoạt động 4: Vận dụng -> [NLS 5.3-a]
  const act4Badge = redFrameContainer({
    text: '[NLS 5.3-a: Sử dụng sáng tạo công nghệ số & AI]',
    colorClass: 'text-red-600',
  });

  // Match Mục tiêu: in Hoạt động 1
  result = result.replace(
    /((?:HOẠT ĐỘNG 1|KHỞI ĐỘNG|MỞ ĐẦU)[\s\S]{0,120}?<b>Mục tiêu:<\/b>|<b>Mục tiêu:<\/b>(?=[\s\S]{0,150}?(?:khởi động|mở đầu)))/gi,
    (match) => {
      if (!match.includes('border-red-500') && !match.includes('[NLS 1.1-a')) {
        return `${match}<br/>${act1Badge}`;
      }
      return match;
    }
  );

  // Match Mục tiêu: in Hoạt động 2
  result = result.replace(
    /((?:HOẠT ĐỘNG 2|HÌNH THÀNH KIẾN THỨC)[\s\S]{0,120}?<b>Mục tiêu:<\/b>|<b>Mục tiêu:<\/b>(?=[\s\S]{0,150}?hình thành kiến thức))/gi,
    (match) => {
      if (!match.includes('border-red-500') && !match.includes('[NLS 3.1-a')) {
        return `${match}<br/>${act2Badge}`;
      }
      return match;
    }
  );

  // Match Mục tiêu: in Hoạt động 3
  result = result.replace(
    /((?:HOẠT ĐỘNG 3|LUYỆN TẬP)[\s\S]{0,120}?<b>Mục tiêu:<\/b>|<b>Mục tiêu:<\/b>(?=[\s\S]{0,150}?luyện tập))/gi,
    (match) => {
      if (!match.includes('border-red-500') && !match.includes('[NLS 2.4-a')) {
        return `${match}<br/>${act3Badge}`;
      }
      return match;
    }
  );

  // Match Mục tiêu: in Hoạt động 4
  result = result.replace(
    /((?:HOẠT ĐỘNG 4|VẬN DỤNG)[\s\S]{0,120}?<b>Mục tiêu:<\/b>|<b>Mục tiêu:<\/b>(?=[\s\S]{0,150}?vận dụng))/gi,
    (match) => {
      if (!match.includes('border-red-500') && !match.includes('[NLS 5.3-a')) {
        return `${match}<br/>${act4Badge}`;
      }
      return match;
    }
  );

  // Fallback: If "Mục tiêu:" exists under an activity title but hasn't received a badge, inject appropriate badge
  result = result.replace(/<b>Mục tiêu:<\/b>(?!\s*<br\/>\s*<div[^>]*border-red-500)/gi, (match, offset, string) => {
    const beforeStr = string.slice(Math.max(0, offset - 200), offset);
    if (/hoạt động 1|khởi động|mở đầu/i.test(beforeStr)) {
      return `<b>Mục tiêu:</b><br/>${act1Badge}`;
    } else if (/hoạt động 2|hình thành kiến thức/i.test(beforeStr)) {
      return `<b>Mục tiêu:</b><br/>${act2Badge}`;
    } else if (/hoạt động 3|luyện tập/i.test(beforeStr)) {
      return `<b>Mục tiêu:</b><br/>${act3Badge}`;
    } else if (/hoạt động 4|vận dụng/i.test(beforeStr)) {
      return `<b>Mục tiêu:</b><br/>${act4Badge}`;
    }
    return match;
  });

  return result;
}

/**
 * Bổ sung miền NLS cần thiết vào cuối mỗi tiết học tại Mục 4 (Hướng dẫn học bài và chuẩn bị bài),
 * đặt ở vị trí khung đỏ chữ nhật ở cuối mỗi tiết học (trước vạch phân cách ------------------- hoặc tiết tiếp theo).
 */
export function formatPart4NlsBottom(htmlStr: string): string {
  if (!htmlStr) return htmlStr;

  let result = htmlStr;

  // Red rectangle badge for Part 4 at the end of each lesson
  const part4Badge = `<div class="my-2 inline-flex flex-wrap items-center gap-2 border border-red-500 rounded px-2.5 py-1 text-xs font-mono font-bold bg-rose-50/20"><span class="text-red-600 font-bold">[NLS 1.3-a: Quản lý, lưu trữ & chuẩn bị học liệu số cho bài học tiếp theo]</span></div>`;

  // 1. Remove any loose NLS badges right next to/under the heading 4. Hướng dẫn học bài...
  result = result.replace(
    /((?:4\.\s*Hướng dẫn học bài|PHẦN IV|PHẦN 4|HƯỚNG DẪN HỌC BÀI VÀ CHUẨN BỊ BÀI|HƯỚNG DẪN VỀ NHÀ|CHUẨN BỊ BÀI SAU|DẶN DÒ)[^<\n]*)(?:\s*<br\s*\/?>)*(?:\s*<div[^>]*border-red-500[^>]*>[\s\S]*?\[NLS 1\.3-a[\s\S]*?<\/div>|\s*<span[^>]*>\[NLS 1\.3-a[^\]]*\]<\/span>)+/gi,
    '$1'
  );

  // 2. Identify sections of Part 4 and append the red rectangular badge at the end of each lesson (before <hr/>, -------------------, Ngày soạn:, TIẾT..., BÀI..., or end of block)
  const part4Pattern = /((?:4\.\s*Hướng dẫn học bài|PHẦN IV|PHẦN 4|HƯỚNG DẪN HỌC BÀI VÀ CHUẨN BỊ BÀI|HƯỚNG DẪN VỀ NHÀ|CHUẨN BỊ BÀI SAU|DẶN DÒ)[\s\S]*?)(?=<hr|-------------------|Ngày soạn:|TIẾT\s+\d+|BÀI\s+\d+|<h[1-4]|$)/gi;

  result = result.replace(part4Pattern, (match) => {
    // If this Part 4 section already contains the red rectangle badge for NLS 1.3-a at the end, keep it
    if (match.includes('border-red-500') && match.includes('NLS 1.3-a')) {
      return match;
    }
    // Trim whitespace and append the red rectangular badge
    const trimmed = match.trimEnd();
    return `${trimmed}\n<br/>${part4Badge}\n`;
  });

  return result;
}

/**
 * Inject appropriate NLS tags directly into group assignment questions/headers (Nhóm 1, 2, Nhóm 3, 4, etc.)
 * as requested (e.g., photo 28 / image 4).
 */
export function injectNlsIntoGroupTasks(htmlStr: string): string {
  if (!htmlStr) return htmlStr;

  let result = htmlStr;

  // 1. Group 1, 2 (or Nhóm 1) assignment -> NLS 2.4-a (Hợp tác qua công nghệ số) - Red + Navy bold text
  result = result.replace(
    /(Nhóm\s+1\s*[,;&\+]\s*2|Nhóm\s+1(?!\s*[,;&\+\d]))\s*:(?!\s*<span[^>]*>)?(?!\s*\[(?:NLS|AI-NL))/gi,
    `$1 <span class="font-mono font-bold text-red-600 border border-slate-300 px-1.5 py-0.5 rounded text-[11px] inline-block my-0.5 mx-1">[NLS 2.4-a: Hợp tác qua công nghệ số]</span>:`
  );

  // 2. Group 3, 4 (or Nhóm 2) assignment -> NLS 1.1-a (Duyệt, tìm kiếm & lọc dữ liệu số) - Red + Navy bold text
  result = result.replace(
    /(Nhóm\s+3\s*[,;&\+]\s*4|Nhóm\s+2(?!\s*[,;&\+\d]))\s*:(?!\s*<span[^>]*>)?(?!\s*\[(?:NLS|AI-NL))/gi,
    `$1 <span class="font-mono font-bold text-red-600 border border-slate-300 px-1.5 py-0.5 rounded text-[11px] inline-block my-0.5 mx-1">[NLS 1.1-a: Duyệt, tìm kiếm & lọc dữ liệu số]</span>:`
  );

  // 3. Any other Nhóm X: assignment if not yet tagged -> NLS 2.4-a
  result = result.replace(
    /(Nhóm\s+\d+(?:\s*[,;&\+]\s*\d+)*)\s*:(?!\s*<span[^>]*>)?(?!\s*\[(?:NLS|AI-NL))/gi,
    `$1 <span class="font-mono font-bold text-red-600 border border-slate-300 px-1.5 py-0.5 rounded text-[11px] inline-block my-0.5 mx-1">[NLS 2.4-a: Hợp tác qua công nghệ số]</span>:`
  );

  // 4. "Câu hỏi cho từng nhóm:" or "Giao nhiệm vụ cho các nhóm:" -> NLS 2.4-a
  result = result.replace(
    /(câu hỏi cho từng nhóm|nhiệm vụ cho các nhóm|giao nhiệm vụ nhóm)\s*:(?!\s*<span[^>]*>)?(?!\s*\[(?:NLS|AI-NL))/gi,
    `$1 <span class="font-mono font-bold text-red-600 border border-slate-300 px-1.5 py-0.5 rounded text-[11px] inline-block my-0.5 mx-1">[NLS 2.4-a: Hợp tác qua công nghệ số]</span>:`
  );

  return result;
}

/**
 * Utility to process and re-align Lesson Plan HTML.
 * Moves NLS tags from Right Column to Left Column if needed,
 * injects NLS tags into group task questions, and removes unwanted synthetic activity banners.
 */
export function relocateNlsToLeftColumn(htmlStr: string): string {
  if (!htmlStr) return htmlStr;

  // Remove synthetic/duplicate banner blocks like [Tích hợp NLS & AI Khởi động...]
  let processed = htmlStr.replace(/<div\b[^>]*>[\s\S]*?\[Tích hợp NLS & AI[^\]]*\][\s\S]*?<\/div>/gi, '');

  // First expand bare NLS codes to include titles (e.g. [NLS 2.4-a: Hợp tác qua công nghệ số])
  processed = expandNlsTagTitles(processed);

  // Inject NLS domain tags into goals section (Mục tiêu) of each activity
  processed = injectNlsActivityGoals(processed);

  // Position NLS integration at the bottom of Part 4 (Hướng dẫn học bài & chuẩn bị bài)
  processed = formatPart4NlsBottom(processed);

  // Inject NLS tags into group assignments (Nhóm 1, 2..., Nhóm 3, 4...)
  processed = injectNlsIntoGroupTasks(processed);

  // Remove background color fills for NLS tags
  processed = stripNlsBackgrounds(processed);

  // Process HTML table rows <tr>...</tr> if table structure exists
  processed = processed.replace(/<tr\b[^>]*>([\s\S]*?)<\/tr>/gi, (fullTrMatch, trContent) => {
    // Extract cells inside this row
    const cellRegex = /<(td|th)\b([^>]*)>([\s\S]*?)<\/\1>/gi;
    const cells: { tag: string; attrs: string; content: string }[] = [];
    let cellMatch;

    while ((cellMatch = cellRegex.exec(trContent)) !== null) {
      cells.push({
        tag: cellMatch[1],
        attrs: cellMatch[2],
        content: cellMatch[3],
      });
    }

    // If row has at least 2 cells (Left = index 0: Tổ chức thực hiện, Right = index 1: Nội dung/Sản phẩm)
    if (cells.length >= 2) {
      const isHeaderRow = /tổ chức thực hiện|sản phẩm|nội dung/i.test(cells[0].content + cells[1].content);
      if (isHeaderRow && cells[0].tag.toLowerCase() === 'th') {
        return fullTrMatch;
      }

      let leftCell = cells[0].content;
      let rightCell = cells[1].content;

      // Extract raw [NLS ...] or [AI-NL...] bracket tags from right cell and move to left cell if any exist
      const nlsTagsToMove: string[] = [];
      rightCell = rightCell.replace(/\[(?:NLS|AI-NL)[^\]]*\]/gi, (tag) => {
        nlsTagsToMove.push(tag);
        return '';
      });

      if (nlsTagsToMove.length > 0) {
        const movedTags = nlsTagsToMove
          .map(t => `<span class="font-mono font-bold text-slate-900 border border-slate-300 px-1.5 py-0.5 rounded text-[11px] inline-block mr-1">${t}</span>`)
          .join(' ');
        
        leftCell = leftCell + `\n<div class="mt-1">${movedTags}</div>`;

        cells[0].content = leftCell;
        cells[1].content = rightCell;

        const trTagMatch = fullTrMatch.match(/^<tr\b[^>]*>/i);
        const trOpenTag = trTagMatch ? trTagMatch[0] : '<tr>';
        
        let rebuiltCells = '';
        for (let i = 0; i < cells.length; i++) {
          rebuiltCells += `<${cells[i].tag}${cells[i].attrs}>${cells[i].content}</${cells[i].tag}>`;
        }
        return trOpenTag + rebuiltCells + '</tr>';
      }
    }

    return fullTrMatch;
  });

  return processed;
}

/**
 * Dynamically extract specific Lesson Title, Topic, or Lesson Number
 * from lesson content HTML or raw text.
 */
export function extractLessonTitle(contentHtml: string, subject: string, grade: string): string {
  if (!contentHtml) {
    const subClean = subject || 'Ngữ văn';
    const grdClean = grade || 'Khối THCS';
    return `Bài dạy ${subClean} (${grdClean}) - Tích hợp NLS`;
  }

  // Strip HTML tags to get plain text lines
  const cleanText = contentHtml
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/p>/gi, '\n')
    .replace(/<\/div>/gi, '\n')
    .replace(/<\/tr>/gi, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ');

  const lines = cleanText
    .split('\n')
    .map(l => l.trim())
    .filter(l => l.length > 2);

  let detectedBai = '';
  let detectedDocVanBan = '';
  let detectedExplicit = '';

  // Non-title boilerplate keywords to filter out
  const isBoilerplate = (str: string) => {
    return /^(TRƯỜNG|PHÒNG GIÁO DỤC|TỔ CHUYÊN MÔN|CÔNG VĂN|THÔNG TƯ|QUYẾT ĐỊNH|BỘ GIÁO DỤC|CỘNG HÒA|ĐỘC LẬP|GIÁO VIÊN|HỌ VÀ TÊN|NGÀY SOẠN|LỚP|SĨ SỐ|I\.|II\.|III\.|IV\.|1\. Kiến thức|1\. Năng lực|MỤC TIÊU|THIẾT BỊ|TIẾN TRÌNH)/i.test(str);
  };

  // Search first 40 lines for explicit markers and key patterns
  for (const line of lines.slice(0, 45)) {
    if (isBoilerplate(line)) continue;

    // 1. Check for "TÊN BÀI DẠY: ...", "KẾ HOẠCH BÀI DẠY: ...", "BÀI DẠY: ...", "TÊN BÀI: ..."
    const matchExplicit = line.match(/(?:TÊN BÀI DẠY|Tên bài dạy|KẾ HOẠCH BÀI DẠY|BÀI DẠY|Bài dạy|TÊN BÀI|Tên bài|TÊN BÀI HỌC)\s*[:\-]\s*(.+)/i);
    if (matchExplicit && matchExplicit[1]?.trim().length > 3) {
      const candidate = matchExplicit[1].trim();
      if (!isBoilerplate(candidate) && candidate.toLowerCase() !== 'tích hợp nls') {
        detectedExplicit = candidate;
        break;
      }
    }

    // 2. Check for "Bài 9: HÔM NAY VÀ NGÀY MAI (13 tiết)", "Bài 1. ...", "Chủ đề 2: ...", "Tiết 12: ..."
    if (!detectedBai) {
      const matchBai = line.match(/^(Bài\s+\d+[^:\n]*:[^\n]+)/i) || 
                       line.match(/^(Bài\s+\d+\.[^\n]+)/i) ||
                       line.match(/^(Chủ đề\s+\d+[^:\n]*:[^\n]+)/i) ||
                       line.match(/^(Tiết\s+\d+[^:\n]*:[^\n]+)/i) ||
                       line.match(/^(Văn bản\s+\d+:[^\n]+)/i);
      if (matchBai && matchBai[1]?.trim().length > 4) {
        detectedBai = matchBai[1].trim();
      }
    }

    // 3. Check for specific text reading title like "B. Đọc văn bản: Nhà thơ của quê hương..." or "Đọc văn bản: ..." or "Văn bản 1: ..."
    if (!detectedDocVanBan) {
      const matchDoc = line.match(/(?:Đọc văn bản|Văn bản|Đọc - tìm hiểu chung|Văn bản 1|Văn bản 2|Văn bản 3)\s*[:\-]\s*([^\n]+)/i);
      if (matchDoc && matchDoc[1]?.trim().length > 3) {
        const val = matchDoc[1].trim();
        if (!/^(i|ii|iii|1|2|3|mục tiêu|thiết bị)/i.test(val)) {
          detectedDocVanBan = `Đọc văn bản: ${val}`;
        }
      }
    }
  }

  // Combine detected components if available
  if (detectedExplicit) {
    return detectedExplicit;
  }

  if (detectedBai && detectedDocVanBan) {
    // Avoid duplication if detectedDocVanBan is already inside detectedBai
    if (detectedBai.toLowerCase().includes(detectedDocVanBan.toLowerCase().replace('đọc văn bản:', '').trim())) {
      return detectedBai;
    }
    return `${detectedBai} - ${detectedDocVanBan}`;
  }

  if (detectedBai) {
    return detectedBai;
  }

  if (detectedDocVanBan) {
    return detectedDocVanBan;
  }

  // Check uppercase headings or lines starting with "BÀI ", "CHỦ ĐỀ ", "NGỮ VĂN "
  for (const line of lines.slice(0, 30)) {
    if (isBoilerplate(line)) continue;
    if (/^(bài|chủ đề|tiết|văn bản)\s+/i.test(line) && line.length > 5 && line.length < 140) {
      return line;
    }
  }

  for (const line of lines.slice(0, 20)) {
    if (isBoilerplate(line)) continue;
    if (line === line.toUpperCase() && line.length >= 8 && line.length <= 100 && !line.includes('CỘNG HÒA')) {
      return line;
    }
  }

  const subClean = subject || 'Ngữ văn';
  const grdClean = grade || 'Khối THCS';
  return `Bài dạy ${subClean} (${grdClean}) - Tích hợp NLS`;
}

/**
 * Format timestamp / dateString into full HH:mm - DD/MM/YYYY display.
 */
export function formatDateTime(dateString: string, createdAt?: number): string {
  if (createdAt && typeof createdAt === 'number' && !isNaN(createdAt) && createdAt > 1000000000) {
    const d = new Date(createdAt);
    const timeStr = d.toLocaleTimeString('vi-VN', { hour: '2-digit', minute: '2-digit' });
    const dateStr = d.toLocaleDateString('vi-VN', { day: '2-digit', month: '2-digit', year: 'numeric' });
    return `${timeStr} - ${dateStr}`;
  }

  if (dateString && dateString.includes(':') && dateString.includes('-')) {
    return dateString;
  }

  // Fallback format current date with time if only date was provided
  const now = new Date();
  const timeStr = now.toLocaleTimeString('vi-VN', { hour: '2-digit', minute: '2-digit' });
  if (dateString) {
    return `${timeStr} - ${dateString}`;
  }
  return `${timeStr} - ${now.toLocaleDateString('vi-VN')}`;
}

